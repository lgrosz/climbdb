#!/usr/bin/env bash
#
# Regenerate schema/schema.sql, a readable snapshot of the deployed schema.
#
# The Sqitch plan is the source of truth. Run this after changing it and commit
# the result alongside the change; never edit the snapshot by hand.
#
# Deploys to a throwaway database, so it needs permission to create databases.
# Connection settings come from the usual PG* environment variables.
#
# pg_dump must be at least as new as the server. To use the server's own copy:
#   PG_DUMP="docker compose exec -T postgres pg_dump -U postgres" scripts/dump-schema.sh

set -euo pipefail

cd "$(dirname "$0")/.."

PG_DUMP="${PG_DUMP:-pg_dump}"

output=schema/schema.sql
db="climbdb_schema_dump_$$"
tmp="$(mktemp)"

cleanup() {
  rm -f "$tmp"
  dropdb --if-exists "$db"
}

createdb "$db"
trap cleanup EXIT

sqitch deploy --chdir schema "db:pg:$db" >&2

{
  echo '-- Generated by scripts/dump-schema.sh from the Sqitch plan. Do not edit.'
  echo
  # The output must not depend on the machine that generated it. The key is
  # fixed because pg_dump otherwise picks a random one on every run, and the
  # version lines are dropped because they differ between installs.
  $PG_DUMP --schema-only --schema=climb --no-owner --restrict-key=climbdb -d "$db" \
    | sed -E '/^-- Dumped (from database version|by pg_dump version) /d'
} > "$tmp"

mv "$tmp" "$output"
